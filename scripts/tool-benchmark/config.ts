/**
 * Sample and iteration budgets, kept identical to `examples/compare_tools`.
 *
 * Every number here appears twice, once per language, because the two engines
 * are separate processes with no shared configuration. The report cross-checks
 * them and fails loudly rather than comparing a hundred TypeScript calls
 * against three Rust ones.
 */

export type Suite = "core" | "hard";

/** How much a single call of a hard case costs, which sets its iteration count. */
export type Weight = "light" | "medium" | "heavy" | "xheavy";

const HARD_ITERATIONS: Record<Weight, [full: number, quick: number]> = {
  light: [20, 5],
  medium: [10, 3],
  heavy: [5, 2],
  xheavy: [3, 1],
};

export function samplesFor(suite: Suite, quick: boolean): number {
  if (suite === "hard") return 3;
  return quick ? 3 : 5;
}

export function coreIterations(kind: "file" | "grep" | "process", quick: boolean): number {
  if (quick) return kind === "file" ? 20 : kind === "grep" ? 3 : 5;
  return kind === "file" ? 100 : kind === "grep" ? 10 : 20;
}

export function hardIterations(weight: Weight, quick: boolean): number {
  const [full, fast] = HARD_ITERATIONS[weight];
  return quick ? fast : full;
}

